def W(id, type, title, x, y, w, h, source, config, **options):
    return {"id": id, "type": type, "title": title, "x": x, "y": y, "w": w, "h": h, "source": source,
            "config": config, "options": options}


def count(*filters, group=None, label="People"):
    c = {"filters": list(filters), "measures": [{"agg": "count", "label": label}]}
    if group:
        c["group_by"] = group if isinstance(group, list) else [group]
    return c


